# Per-file population driver
# ══════════════════════════════════════════════════════════════════════════════

def populate_file(
    path:            Path,
    tf:              str,
    force:           bool,
    logger:          logging.Logger,
) -> Dict:
    logger.info("  Loading %s", path)
    df = pd.read_csv(path, low_memory=False)
    rows_before = len(df)

    # Determine which targets need computing
    all_targets = list(TARGET_COLS)
    if tf not in PIVOT_SKIP_TFS:
        all_targets += PIVOT_COLS

    need = [c for c in all_targets if c in df.columns and (_is_unpopulated(df[c]) or force)]
    skip = [c for c in all_targets if c in df.columns and c not in need]

    logger.info("    %d target cols need population, %d already done", len(need), len(skip))
    if not need:
        logger.info("    All targets populated — skipping file.")
        return {"touched": 0, "skipped": len(skip)}

    # ── Compute all indicators ─────────────────────────────────────────────
    touched = 0

    def _write(col: str, values):
        nonlocal touched
        if col in df.columns and col in need:
            df[col] = values
            touched += 1

    # Returns & volatility
    log_ret    = _compute_log_return(df["close"])
    vol_ewma   = _compute_vol_ewma(df["close"])
    vol_energy = _compute_curvature_energy(df["close"])

    _write("log_return",  log_ret)
    _write("vol_ewma",    vol_ewma)
    _write("vol_energy",  vol_energy)
    _write("ret_z",       (log_ret / (vol_ewma + 1e-12)).astype(np.float32))

    # BB dynamic
    bb = _compute_bb_dynamic(df)
    for col in ["bb_mu_dyn", "bb_sigma_dyn", "bb_lower_dyn", "bb_upper_dyn",
                "bandwidth", "bw_expansion_rate"]:
        _write(col, bb[col])

    # SMA / MA
    _write("sma", _compute_sma(df["close"]))
    _write("MA",  _compute_ma(df["close"]))

    # FRAMA
    _write("FRAMA", _compute_frama(df["close"]))

    # WeightedAlpha
    _write("WeightedAlpha", _compute_weighted_alpha(df["close"]))

    # AnchoredVWAP
    _write("AnchoredVWAP", _compute_anchored_vwap(df))

    # TrendSeekers
    ts = _compute_trend_seekers(df)
    _write("TrendSeekerUp",   ts["TrendSeekerUp"])
    _write("TrendSeekerDown", ts["TrendSeekerDown"])

    # Donchian
    don = _compute_donchian(df)
    _write("TurtleChn-Up",  don["TurtleChn-Up"])
    _write("TurtleChn-Low", don["TurtleChn-Low"])

    # AccDist
    ad = _compute_acc_dist(df)
    _write("AccDistWill",       ad["AccDistWill"])
    _write("AccDistWillMovAvg", ad["AccDistWillMovAvg"])

    # OSC-Volume
    _write("OSC-Volume", _compute_osc_volume(df))

    # Wilder ASI
    _write("WilderAccSwingIndex", _compute_wilder_asi(df))

    # ATR_recon
    _write("ATR_recon", _compute_atr_recon(df))

    # Time of day
    tod = _compute_tod(df)
    _write("tod_sin", tod["tod_sin"])
    _write("tod_cos", tod["tod_cos"])

    # Friction OK flags
    fok = _compute_friction_ok(df)
    for col in ["friction_ok_5", "friction_ok_10", "friction_ok_20",
                "friction_ok_40", "friction_ok_60"]:
        _write(col, fok[col])

    # Regime persistence
    _write("regime_persistence", _compute_regime_persistence(df))

    # Price stretch & zones (uses BB already computed)
    ps = _compute_price_stretch(df, bb)
    _write("price_stretch", ps)
    _write("stretch_zone",  _compute_stretch_zone(ps))
    _write("ivr_zone",      _compute_ivr_zone(df))
    _write("reversal_score", _compute_reversal_score(df))

    # Target spot
    _write("target_spot", _compute_target_spot(df))

    # Pivot analytics (skip for m5)
    if tf not in PIVOT_SKIP_TFS:
        any_pivot_needed = any(c in need for c in PIVOT_COLS)
        if any_pivot_needed:
            logger.info("    Computing pivot analytics for %s…", tf)
            piv = _compute_pivot_analytics(df, tf)
            for col in PIVOT_COLS:
                if col in piv.columns:
                    _write(col, piv[col])

    # ── Validate & write ─────────────────────────────────────────────────
    assert len(df) == rows_before, "Row count changed during population"
    df.to_csv(path, index=False)
    logger.info("    Wrote %d columns → %s", touched, path.name)
    return {"touched": touched, "skipped": len(skip)}


