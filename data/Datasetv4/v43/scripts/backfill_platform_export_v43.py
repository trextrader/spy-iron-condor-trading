# ── Williams A/D & AccDist ────────────────────────────────────────────────────

def _compute_acc_dist(df: pd.DataFrame) -> pd.DataFrame:
    close    = df["close"]
    high     = df["high"]
    low      = df["low"]
    prev_c   = close.shift(1).fillna(close.iloc[0])
    t_high   = pd.concat([high, prev_c], axis=1).max(axis=1)
    t_low    = pd.concat([low,  prev_c], axis=1).min(axis=1)
    diff     = close.diff().fillna(0.0)
    ad_val   = np.where(diff > 0, close - t_low,
               np.where(diff < 0, close - t_high, 0.0))
    ad_ser   = pd.Series(ad_val, index=close.index)
    acc      = ad_ser.cumsum()
    acc_ma   = acc.ewm(span=14, min_periods=1, adjust=False).mean()
    res = pd.DataFrame(index=df.index)
    res["AccDistWill"]       = acc.astype(np.float32)
    res["AccDistWillMovAvg"] = acc_ma.astype(np.float32)
    return res


# ── OSC-Volume ────────────────────────────────────────────────────────────────

def _compute_osc_volume(df: pd.DataFrame) -> pd.Series:
    """Volume oscillator: fast EMA(5) - slow EMA(20) raw difference."""
    vol      = df["volume"].astype(np.float64)
    fast_ema = vol.ewm(span=5,  adjust=False).mean()
    slow_ema = vol.ewm(span=20, adjust=False).mean()
    return (fast_ema - slow_ema).astype(np.float32)


# ── Wilder Accumulation Swing Index ──────────────────────────────────────────

def _compute_wilder_asi(df: pd.DataFrame) -> pd.Series:
    """Wilder's Accumulative Swing Index (simplified, no limit-move scaling)."""
    close  = df["close"].values.astype(np.float64)
    open_  = df["open"].values.astype(np.float64)
    high   = df["high"].values.astype(np.float64)
    low    = df["low"].values.astype(np.float64)
    n      = len(close)

    si  = np.zeros(n, dtype=np.float64)
    asi = np.zeros(n, dtype=np.float64)

    for i in range(1, n):
        pc   = close[i - 1]
        po   = open_[i - 1]
        R1   = abs(high[i] - pc)
        R2   = abs(low[i]  - pc)
        R3   = high[i] - low[i]
        R    = max(R1, R2, R3, 1e-10)
        num  = (close[i] - pc
                + 0.5 * (close[i] - open_[i])
                + 0.25 * (pc - po))
        si[i]  = num / R
        asi[i] = asi[i - 1] + si[i]

    return pd.Series(asi, index=df.index).astype(np.float32)


# ── ATR Recon ─────────────────────────────────────────────────────────────────

def _compute_atr_recon(df: pd.DataFrame) -> pd.Series:
    """Absolute ATR = atr_pct × close."""
    if "atr_pct" in df.columns and not _is_unpopulated(df["atr_pct"]):
        atr_pct = df["atr_pct"]
    else:
        atr_pct = _compute_atr(df) / df["close"]
    return (atr_pct * df["close"]).astype(np.float32)


# ── Time of Day ───────────────────────────────────────────────────────────────

def _compute_tod(df: pd.DataFrame) -> pd.DataFrame:
    """Cyclical time-of-day encoding over the regular session (9:30–16:00 ET)."""
    ts   = pd.to_datetime(df["timestamp"])
    mins = (ts.dt.hour - 9) * 60 + ts.dt.minute - 30  # minutes since 9:30
    frac = mins.clip(0, 389).astype(float) / 390.0
    res  = pd.DataFrame(index=df.index)
    res["tod_sin"] = np.sin(2 * np.pi * frac).astype(np.float32)
    res["tod_cos"] = np.cos(2 * np.pi * frac).astype(np.float32)
    return res


# ── Friction OK flags ─────────────────────────────────────────────────────────

def _compute_friction_ok(df: pd.DataFrame) -> pd.DataFrame:
    """Binary flags: fraction of last N bars with spread_ratio < 0.01."""
    if "spread_ratio" in df.columns and not _is_unpopulated(df["spread_ratio"]):
        sr = df["spread_ratio"].fillna(1.0)
    else:
        mid = (df["high"] + df["low"]) / 2 + 1e-12
        sr  = (df["high"] - df["low"]) / mid
    liquid = (sr < 0.01).astype(float)
    res = pd.DataFrame(index=df.index)
    for w in (5, 10, 20, 40, 60):
        ok = (liquid.rolling(w, min_periods=1).mean() >= 0.8).astype(np.float32)
        res[f"friction_ok_{w}"] = ok
    return res


# ── Regime Persistence ────────────────────────────────────────────────────────

def _compute_regime_persistence(df: pd.DataFrame) -> pd.Series:
    """
    Running count of consecutive bars in the same PSAR trend direction,
    normalised by rolling max count (∈ [0, 1]).
    """
    if "psar_trend" in df.columns and not _is_unpopulated(df["psar_trend"]):
        trend = df["psar_trend"].fillna(1.0)
    else:
        from scripts.indicators.psar_adaptive import compute_psar_full
        psar  = compute_psar_full(df["high"], df["low"], df["close"])
        trend = psar["psar_trend"]

    t   = trend.values
    cnt = np.ones(len(t), dtype=np.float64)
    for i in range(1, len(t)):
        if t[i] == t[i - 1]:
            cnt[i] = cnt[i - 1] + 1.0
    cnt_ser  = pd.Series(cnt, index=df.index)
    roll_max = cnt_ser.rolling(252, min_periods=1).max()
    return (cnt_ser / roll_max).clip(0.0, 1.0).astype(np.float32)


# ── Price Stretch & Zones ─────────────────────────────────────────────────────

def _compute_price_stretch(df: pd.DataFrame, bb: pd.DataFrame) -> pd.Series:
    """Normalised price position within Bollinger bands: (close - mu) / (2σ)."""
    mu    = bb["bb_mu_dyn"]
    sigma = bb["bb_sigma_dyn"]
    return ((df["close"] - mu) / (2.0 * sigma + 1e-8)).astype(np.float32)

def _compute_stretch_zone(price_stretch: pd.Series) -> pd.Series:
    """1 if |price_stretch| > 0.5 (outside Bollinger bands), else 0."""
    return (price_stretch.abs() > 0.5).astype(np.float32)

def _compute_ivr_zone(df: pd.DataFrame) -> pd.Series:
    """
    Vol percentile zone: 1=low, 2=mid, 3=high (rolling 252-bar vol_ewma quantiles).
    """
    vol = _compute_vol_ewma(df["close"])
    q33 = vol.rolling(252, min_periods=1).quantile(0.33)
    q67 = vol.rolling(252, min_periods=1).quantile(0.67)
    zone = np.where(vol < q33, 1, np.where(vol < q67, 2, 3))
    return pd.Series(zone, index=df.index).astype(np.float32)

def _compute_reversal_score(df: pd.DataFrame) -> pd.Series:
    """
    Reversal probability in [0, 1].
    Derived from breakout_score (∈ {-1, 0, +1}):
      reversal_score = (breakout_score × -0.5 + 0.5).clip(0, 1)
    High reversal_score when price is at or below lower band.
    """
    if "breakout_score" in df.columns and not _is_unpopulated(df["breakout_score"]):
        bs = df["breakout_score"]
    else:
        from scripts.indicators.reversal_stack import compute_reversal_stack
        stk = compute_reversal_stack(df["high"], df["low"], df["close"])
        bs  = stk["breakout_score"]
    return (-bs * 0.5 + 0.5).clip(0.0, 1.0).astype(np.float32)


# ── Target Spot ───────────────────────────────────────────────────────────────

def _compute_target_spot(df: pd.DataFrame, fwd_bars: int = 5) -> pd.Series:
    """5-bar forward log return × 100."""
    fwd  = df["close"].shift(-fwd_bars)
    ret  = np.where(
        (fwd > 0) & (df["close"] > 0),
        np.log(fwd / df["close"]) * 100.0,
        0.0,
    )
    return pd.Series(ret, index=df.index).astype(np.float32)


# ── Pivot Analytics ───────────────────────────────────────────────────────────

def _compute_pivot_analytics(df: pd.DataFrame, tf: str) -> pd.DataFrame:
    """
    Pivot detection + extended pivot analytics for m1, m15, h1.
    (m5 Pivot cols are all-NaN by design in 2025 reference — skip via caller.)
    """
    from scripts.indicators.psar_adaptive import compute_psar_full  # noqa

    close = df["close"]
    high  = df["high"]
    low   = df["low"]
    n     = len(close)
    mins_per_bar = TF_MINUTES[tf]

    # ── ATR for adaptive lookback ──
    if "atr_pct" in df.columns and not _is_unpopulated(df["atr_pct"]):
        atr14_pct = df["atr_pct"].values.astype(np.float64)
    else:
        atr14_pct = (_compute_atr(df, 14) / close).values.astype(np.float64)
    atr14_abs = atr14_pct * close.values.astype(np.float64)

    # Adaptive lookback: shorter in high vol, longer in low vol
    atr_s   = pd.Series(atr14_abs).rolling(200, min_periods=1).median().values
    atr_rat = np.clip(atr14_abs / (atr_s + 1e-12), 0.5, 3.0)
    base_lb = 5
    adap_lb = np.clip((base_lb / atr_rat).astype(int), 2, base_lb * 3)

    h = high.values.astype(np.float64)
    l = low.values.astype(np.float64)
    c = close.values.astype(np.float64)

    pivot_high = np.zeros(n, dtype=np.float32)
    pivot_low  = np.zeros(n, dtype=np.float32)
    slope_arr  = np.zeros(n, dtype=np.float64)

    last_price = c[0]
    last_idx   = 0

    for i in range(base_lb, n - base_lb):
        lb = int(min(adap_lb[i], i, n - i - 1))
        lb = max(lb, 2)

        # Local high pivot
        win_h = h[i - lb: i + lb + 1]
        if h[i] == win_h.max():
            pivot_high[i] = 1.0
            if i > last_idx:
                slope_arr[i] = (h[i] - last_price) / max(i - last_idx, 1)
                last_price    = h[i]
                last_idx      = i

        # Local low pivot
        win_l = l[i - lb: i + lb + 1]
        if l[i] == win_l.min():
            pivot_low[i] = 1.0
            if i > last_idx:
                slope_arr[i] = (l[i] - last_price) / max(i - last_idx, 1)
                last_price    = l[i]
                last_idx      = i

    slope_s = pd.Series(slope_arr, index=close.index)
    slope_s = slope_s.replace(0.0, np.nan).ffill().fillna(0.0)

    # Extended analytics
    ph_series = pd.Series(pivot_high, index=close.index)
    pl_series = pd.Series(pivot_low,  index=close.index)

    # ATR-normalised slope
    slope_atr = (slope_s / (atr14_abs + 1e-10)).astype(np.float32)

    # Bars since last pivot (high or low)
    any_pivot = (ph_series + pl_series).clip(0, 1)
    bars_since = np.zeros(n, dtype=np.float32)
    cnt = 0
    for i in range(n):
        if any_pivot.iloc[i] > 0:
            cnt = 0
        else:
            cnt += 1
        bars_since[i] = float(cnt)
    bars_since_s = pd.Series(bars_since, index=close.index)

    # Trend line residual: close minus linear interpolation between pivot prices
    # Approximation: close - (slope × bars_since + last_pivot_close)
    last_piv_price = np.full(n, c[0], dtype=np.float64)
    last_piv_idx_v = np.zeros(n, dtype=np.float64)
    last_piv_val   = c[0]
    last_piv_i     = 0
    for i in range(n):
        if any_pivot.iloc[i] > 0:
            last_piv_val = c[i]
            last_piv_i   = i
        last_piv_price[i] = last_piv_val
        last_piv_idx_v[i] = float(last_piv_i)

    trend_line = last_piv_price + slope_s.values * (np.arange(n) - last_piv_idx_v)
    residual   = c - trend_line
    resid_s    = pd.Series(residual, index=close.index)
    resid_std  = resid_s.rolling(252, min_periods=1).std() + 1e-12
    resid_z    = (resid_s / resid_std).astype(np.float32)
    resid_atr  = (resid_s / (atr14_abs + 1e-10)).astype(np.float32)

    # Curvature proxy: 2nd derivative of slope
    curve      = slope_s.diff().diff().fillna(0.0)
    curve_atr  = (curve / (atr14_abs + 1e-10)).astype(np.float32)

    # Segment stats (between consecutive pivots)
    seg_len_bars = bars_since_s + 1.0
    seg_len_mins = (seg_len_bars * mins_per_bar).astype(np.float32)

    # Segment residual std: rolling std within current segment (approx last N bars)
    seg_max_bars = int(seg_len_bars.max()) if len(seg_len_bars) > 0 else 20
    seg_max_bars = min(max(seg_max_bars, 5), 200)
    seg_resid_std = resid_s.rolling(seg_max_bars, min_periods=1).std().fillna(0.0)
    seg_vol = pd.Series(
        _compute_vol_ewma(close).values,
        index=close.index
    ).rolling(seg_max_bars, min_periods=1).mean()

    res = pd.DataFrame(index=close.index)
    res["PivotHigh"]               = ph_series.astype(np.float32)
    res["PivotLow"]                = pl_series.astype(np.float32)
    res["Slope"]                   = slope_s.astype(np.float32)
    res["SlopeATR"]                = slope_atr
    res["PivotResidual"]           = resid_s.astype(np.float32)
    res["PivotResidualZ"]          = resid_z
    res["PivotCurvatureProxy"]     = curve.astype(np.float32)
    res["PivotResidualATR"]        = resid_atr
    res["PivotCurvatureATR"]       = curve_atr
    res["PivotSegmentLengthBars"]  = seg_len_bars.astype(np.float32)
    res["PivotSegmentLengthMinutes"] = seg_len_mins
    res["PivotSegmentResidualStd"] = seg_resid_std.astype(np.float32)
    res["PivotSegmentVolatility"]  = seg_vol.astype(np.float32)
    return res


