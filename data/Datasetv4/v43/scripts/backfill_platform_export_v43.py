# ── Returns & Volatility ──────────────────────────────────────────────────────

def _compute_log_return(close: pd.Series) -> pd.Series:
    return np.log(close / close.shift(1)).astype(np.float32)

def _compute_vol_ewma(close: pd.Series, span: int = 64) -> pd.Series:
    r = np.log(close / close.shift(1))
    return np.sqrt((r ** 2).ewm(span=span, adjust=False).mean()).astype(np.float32)

def _compute_curvature_energy(close: pd.Series, span: int = 64) -> pd.Series:
    r    = np.log(close / close.shift(1))
    dr   = r.diff()
    d2r  = dr.diff()
    scl  = dr.abs().ewm(span=span, adjust=False).mean() + 1e-12
    kappa = (d2r / scl).ewm(span=max(8, span // 4), adjust=False).mean()
    return np.log1p(kappa.abs()).astype(np.float32)

def _compute_atr(df: pd.DataFrame, period: int = 14) -> pd.Series:
    h, l, c = df["high"], df["low"], df["close"]
    prev_c  = c.shift(1)
    tr = pd.concat([h - l, (h - prev_c).abs(), (l - prev_c).abs()], axis=1).max(axis=1)
    return tr.ewm(alpha=1 / period, adjust=False).mean()


# ── Bollinger Bands (dynamic) ─────────────────────────────────────────────────

def _compute_bb_dynamic(df: pd.DataFrame) -> pd.DataFrame:
    close, high, low = df["close"], df["high"], df["low"]
    vol_energy = _compute_curvature_energy(close)
    mu         = close.rolling(20, min_periods=1).mean()
    sigma      = close.rolling(20, min_periods=1).std(ddof=0).fillna(0)
    g          = (1.0 + vol_energy).clip(lower=1.0)
    sigma_dyn  = sigma * g
    bw         = sigma_dyn
    bw_min     = bw.rolling(100, min_periods=1).min()
    bw_max     = bw.rolling(100, min_periods=1).max()
    bb_pct     = 100 * (bw - bw_min) / (bw_max - bw_min + 1e-12)
    bw_exp     = bw.pct_change(5).fillna(0)
    res = pd.DataFrame(index=close.index)
    res["bb_mu_dyn"]        = mu.astype(np.float32)
    res["bb_sigma_dyn"]     = sigma_dyn.astype(np.float32)
    res["bb_lower_dyn"]     = (mu - 2.0 * sigma_dyn).astype(np.float32)
    res["bb_upper_dyn"]     = (mu + 2.0 * sigma_dyn).astype(np.float32)
    res["bandwidth"]        = bw.astype(np.float32)
    res["bw_expansion_rate"]= bw_exp.clip(-1, 1).astype(np.float32)
    return res


# ── Adaptive SMA & EMA ────────────────────────────────────────────────────────

def _compute_sma(close: pd.Series) -> pd.Series:
    log_ret    = np.log(close / close.shift(1))
    vol        = log_ret.rolling(64, min_periods=1).std()
    vol_med    = vol.rolling(256, min_periods=1).median()
    vol_ratio  = (vol / (vol_med + 1e-12)).clip(0.5, 3.0)
    alpha_med  = float((2.0 / (20.0 / vol_ratio + 1)).median())
    alpha_med  = float(np.clip(alpha_med, 0.01, 0.99))
    return close.ewm(alpha=alpha_med, adjust=False).mean().astype(np.float32)

def _compute_ma(close: pd.Series) -> pd.Series:
    """200-period EMA (long-trend reference)."""
    return close.ewm(span=200, adjust=False).mean().astype(np.float32)


# ── FRAMA ─────────────────────────────────────────────────────────────────────

def _compute_frama(close: pd.Series, window: int = 16) -> pd.Series:
    """
    Fractal Adaptive Moving Average.
    Vectorized rolling max/min pre-computation + sequential EMA pass.
    """
    c    = close.values.astype(np.float64)
    n    = len(c)
    half = window // 2
    s    = pd.Series(c, index=close.index)

    # Rolling extremes for each window half (vectorized)
    h2 = s.shift(1).rolling(half, min_periods=half).max().values
    l2 = s.shift(1).rolling(half, min_periods=half).min().values
    h1 = s.shift(half + 1).rolling(half, min_periods=half).max().values
    l1 = s.shift(half + 1).rolling(half, min_periods=half).min().values
    h3 = s.shift(1).rolling(window, min_periods=window).max().values
    l3 = s.shift(1).rolling(window, min_periods=window).min().values

    N1 = (h1 - l1) / half
    N2 = (h2 - l2) / half
    N3 = (h3 - l3) / window

    with np.errstate(divide="ignore", invalid="ignore"):
        num   = N1 + N2
        denom = np.where(N3 > 1e-10, N3, np.nan)
        ratio = np.where(num > 1e-10, num / denom, np.nan)
        D = np.where(ratio > 0, np.log(ratio) / np.log(2.0), 1.0)
    D     = np.where(np.isfinite(D), D, 1.0)
    alpha = np.clip(np.exp(-4.6 * (D - 1.0)), 0.01, 1.0)
    alpha = np.where(np.isfinite(alpha), alpha, 1.0)

    # Sequential EMA (FRAMA recurrence requires sequential pass)
    frama = c.copy()
    for i in range(1, n):
        if i >= window + half and np.isfinite(alpha[i]):
            frama[i] = alpha[i] * c[i] + (1.0 - alpha[i]) * frama[i - 1]

    return pd.Series(frama, index=close.index).astype(np.float32)


# ── WeightedAlpha ─────────────────────────────────────────────────────────────

def _compute_weighted_alpha(close: pd.Series, n: int = 252) -> pd.Series:
    """252-bar absolute price difference (scale-matched to 2025 reference)."""
    return close.diff(n).astype(np.float32)


# ── AnchoredVWAP ──────────────────────────────────────────────────────────────

def _compute_anchored_vwap(df: pd.DataFrame) -> pd.Series:
    """Rolling daily-reset VWAP."""
    ts   = pd.to_datetime(df["timestamp"])
    date = ts.dt.date
    pv   = df["close"] * df["volume"]
    cum_pv  = pv.groupby(date).cumsum()
    cum_vol = df["volume"].groupby(date).cumsum()
    return (cum_pv / (cum_vol + 1e-12)).astype(np.float32)


