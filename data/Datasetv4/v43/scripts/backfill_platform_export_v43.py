# Main
# ══════════════════════════════════════════════════════════════════════════════

def main() -> int:
    ap = argparse.ArgumentParser(
        description="Backfill all remaining platform-export indicator columns for 2020-2024 v43 datasets."
    )
    ap.add_argument("--base-dir", default=str(_PROJECT_ROOT / "data" / "Datasetv4" / "v43"))
    ap.add_argument("--shells-dir", default=None)
    ap.add_argument("--years",      nargs="+", type=int, default=YEARS)
    ap.add_argument("--timeframes", nargs="+",           default=TIMEFRAMES)
    ap.add_argument(
        "--force-all-targets",
        action="store_true",
        help="Recompute all target columns even if already populated.",
    )
    ap.add_argument("--log",
        default=str(_PROJECT_ROOT / "logs" / "backfill_platform_export_v43.log"))
    ap.add_argument("--summary-json",
        default=str(_PROJECT_ROOT / "reports" / "population_audit"
                    / "backfill_platform_export_summary.json"))
    args = ap.parse_args()

    base_dir   = Path(args.base_dir)
    shells_dir = Path(args.shells_dir) if args.shells_dir else base_dir / "normalized_shells"
    log_path   = Path(args.log)
    sum_json   = Path(args.summary_json)
    sum_json.parent.mkdir(parents=True, exist_ok=True)

    logger = setup_logger(log_path)
    logger.info("=" * 70)
    logger.info("backfill_platform_export_v43.py")
    logger.info("base_dir  : %s", base_dir)
    logger.info("shells_dir: %s", shells_dir)
    logger.info("years     : %s", args.years)
    logger.info("timeframes: %s", args.timeframes)
    logger.info("force     : %s", args.force_all_targets)
    logger.info("=" * 70)

    summary: List[Dict] = []
    total_touched = 0

    for tf in args.timeframes:
        for year in args.years:
            p = shells_dir / str(year) / f"{tf}_dataset_v43_{year}.csv"
            if not p.exists():
                logger.warning("Missing: %s", p)
                continue

            logger.info("[%s %d]", tf, year)
            try:
                result = populate_file(p, tf, args.force_all_targets, logger)
                result.update({"year": year, "timeframe": tf, "file": str(p)})
                summary.append(result)
                total_touched += result["touched"]
            except Exception as exc:
                logger.error("  FAILED %s %d: %s", tf, year, exc, exc_info=True)
                summary.append({
                    "year": year, "timeframe": tf, "file": str(p),
                    "error": str(exc),
                })

    with open(sum_json, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    logger.info("=" * 70)
    logger.info("Backfill complete — total columns touched: %d", total_touched)
    logger.info("Summary JSON: %s", sum_json)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
